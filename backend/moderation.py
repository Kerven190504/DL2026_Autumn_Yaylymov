"""
Простейший фильтр от откровенного треша в предложенных локациях.

Это НЕ полноценная модерация (нет очереди на проверку человеком, нет
защиты от обхода через опечатки/транслит) — просто список явно
нежелательных слов, чтобы отсеять самые грубые попытки. Честно
описано как ограничение в README.md.
"""
import re

_BLOCKED_TERMS = {
    # русский мат и грубые оскорбления (базовый набор корней)
    "хуй", "хуе", "хуё", "пизд", "ебан", "еба", "заеб", "муда", "мудак",
    "сука", "сучк", "долбоеб", "долбоёб", "гандон", "уебок", "уёбок",
    "пидор", "пидар", "залуп", "черт возьми",
    # english profanity/slurs (базовый набор)
    "fuck", "shit", "bitch", "asshole", "cunt", "nigger", "faggot",
    "retard", "whore", "slut",
}


def contains_blocked_terms(*texts: str) -> bool:
    """Регистронезависимая проверка по вхождению подстроки."""
    combined = " ".join(texts).lower()
    combined = re.sub(r"[^a-zа-яё0-9\s]", "", combined)  # немного усложняем обход спецсимволами
    return any(term in combined for term in _BLOCKED_TERMS)
