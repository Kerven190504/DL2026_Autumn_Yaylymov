def get_locations_by_category(category: str | None):
    if not category or category == "all":
        return LOCATIONS
    return [loc for loc in LOCATIONS if loc["category"] == category]


def get_localized(loc: dict, field: str, lang: str) -> str:
    """`_en`-версия поля с падением на русский, если перевода нет —
    это и есть случай локаций от игроков (см. модуль docstring)."""
    if lang == "en":
        return loc.get(f"{field}_en") or loc.get(field, "")
    return loc.get(field, "")
